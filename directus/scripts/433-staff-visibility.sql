-- 433 — coaches and team responsibles who don't play: their absences, and each other.
--
-- WHY
-- ---
-- Follow-up to 429 and the 28.10.2026 member_teams audit (a non-playing VB H2/H3
-- coach). Three reads still keyed on the PLAYER roster (`member_teams`), so a
-- coach / TR without a roster row was invisible on them:
--   1. Absences — Member policy reads them through SAME_TEAM_AS_ME (a shared active
--      roster row). A non-playing coach's absences were invisible to their own
--      players and to their co-coaches.
--   2. RSVPs between co-staff — 429 materialised a staff member's training/game
--      RSVPs for the team's ROSTER only. A head coach who doesn't play could not
--      read the assistant coach's answer (LEADER's COACH_OR_TR_OF_PARTICIPATION
--      walks the participant's member_teams).
--   3. Contact details between co-staff — LEADER's members read (COACH_TEAM_MEMBERS)
--      walks member_teams too: a coach could not read the assistant's phone/email.
--
-- HOW
-- ---
-- Not as filters. Each would be another to-many sibling branch walking
-- member → teams_coaches/teams_responsibles → teams → … , the shape that
-- cross-multiplies (26.08 outage; SCALE NOTE on the LEADER absences rule), and
-- dev cannot even evaluate filtered permissions (keyless). Same method as 341/429:
-- materialise (row, viewer_user) pairs, serve them with ONE one-hop branch.
--   1. absence_visibility (absence, viewer_user): absences of a coach / TR of an
--      ACTIVE team T who is NOT on T's roster → T's roster ∪ T's other staff.
--      setup-permissions: Member absences read gains `visible_to`.
--   2. participation_visibility_expected: the 429 staff branch's viewers become
--      roster ∪ the team's other staff. No policy change (the alias is already
--      in both the Member and the LEADER read).
--   3. member_staff_visibility (member, viewer_user): every pair of co-staff on an
--      ACTIVE team. setup-permissions: LEADER members read gains `staff_visible_to`
--      (same LEADER_TEAM_MEMBER_FIELDS a coach reads for their players).
--
-- Narrow by construction: active teams only (the F44 rule), the person themselves
-- excluded, viewers need a login. Full reconcile per statement (no delta logic —
-- 341's rule); the tables are small (dev clone 29.10.2026: see the backfill counts).
--
-- ⚠⚠ Single-column `id` PK + UNIQUE pair from the start — a composite PK makes
-- Directus ignore the collection and 500 every read of the parent (343).
-- ⚠⚠ Raw directus_fields inserts don't bust the schema cache: RESTART the
-- container after this migration, BEFORE setup-permissions references the aliases.

BEGIN;

-- ── 1. absence_visibility ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS absence_visibility (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  absence     integer NOT NULL REFERENCES absences(id) ON DELETE CASCADE,
  viewer_user uuid    NOT NULL REFERENCES directus_users(id) ON DELETE CASCADE,
  CONSTRAINT absence_visibility_pair_uniq UNIQUE (absence, viewer_user)
);
-- The policy compares viewer_user to $CURRENT_USER.
CREATE INDEX IF NOT EXISTS absence_visibility_viewer_idx ON absence_visibility (viewer_user);

CREATE OR REPLACE VIEW absence_visibility_expected AS
WITH staff AS (
  SELECT tc.teams_id AS team, tc.members_id AS member FROM teams_coaches tc
  UNION
  SELECT tr.teams_id, tr.members_id FROM teams_responsibles tr
)
SELECT DISTINCT a.id AS absence, viewer."user" AS viewer_user
  FROM absences a
  JOIN staff s        ON s.member = a.member
  JOIN teams t        ON t.id = s.team AND t.active
  JOIN (SELECT team, member FROM member_teams
        UNION
        SELECT team, member FROM staff) r ON r.team = s.team AND r.member <> a.member
  JOIN members viewer ON viewer.id = r.member
 WHERE viewer."user" IS NOT NULL
   -- On T's roster → SAME_TEAM_AS_ME already shows it to T.
   AND NOT EXISTS (SELECT 1 FROM member_teams own
                    WHERE own.team = s.team AND own.member = a.member);

CREATE OR REPLACE FUNCTION verify_absence_visibility()
RETURNS TABLE (kind text, absence integer, viewer_user uuid)
LANGUAGE sql STABLE AS $$
  SELECT 'missing'::text, e.absence, e.viewer_user
    FROM absence_visibility_expected e
    LEFT JOIN absence_visibility a ON a.absence = e.absence AND a.viewer_user = e.viewer_user
   WHERE a.absence IS NULL
  UNION ALL
  SELECT 'extra'::text, a.absence, a.viewer_user
    FROM absence_visibility a
    LEFT JOIN absence_visibility_expected e ON e.absence = a.absence AND e.viewer_user = a.viewer_user
   WHERE e.absence IS NULL;
$$;

CREATE OR REPLACE FUNCTION refresh_absence_visibility()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM absence_visibility a
   WHERE NOT EXISTS (SELECT 1 FROM absence_visibility_expected e
                      WHERE e.absence = a.absence AND e.viewer_user = a.viewer_user);
  INSERT INTO absence_visibility (absence, viewer_user)
  SELECT e.absence, e.viewer_user FROM absence_visibility_expected e
  ON CONFLICT (absence, viewer_user) DO NOTHING;
END $$;

-- ── 2. participation_visibility: co-staff see each other's RSVPs ────────────
CREATE OR REPLACE VIEW participation_visibility_expected AS
WITH guest_games AS (
  SELECT DISTINCT game AS game_id FROM game_guests
),
audience AS (
  SELECT gg.game_id, m.id AS member_id, m."user" AS viewer_user
    FROM guest_games gg
    JOIN games g   ON g.id = gg.game_id
    JOIN member_teams mt ON mt.team = g.kscw_team
    JOIN teams t   ON t.id = mt.team AND t.active
    JOIN members m ON m.id = mt.member
  UNION
  SELECT gg.game_id, m.id, m."user"
    FROM guest_games gg
    JOIN game_guests x ON x.game = gg.game_id
    JOIN members m     ON m.id = x.member
  UNION
  SELECT gg.game_id, m.id, m."user"
    FROM guest_games gg
    JOIN games g ON g.id = gg.game_id
    JOIN teams_coaches tc ON tc.teams_id = g.kscw_team
    JOIN members m ON m.id = tc.members_id
  UNION
  SELECT gg.game_id, m.id, m."user"
    FROM guest_games gg
    JOIN games g ON g.id = gg.game_id
    JOIN teams_responsibles tr ON tr.teams_id = g.kscw_team
    JOIN members m ON m.id = tr.members_id
),
guest_rows AS (
  SELECT p.id AS participation, v.viewer_user
    FROM participations p
    JOIN audience s ON s.member_id = p.member
                   AND p.activity_type = 'game'
                   AND p.activity_id = s.game_id::varchar
    JOIN audience v ON v.game_id = s.game_id
   WHERE v.viewer_user IS NOT NULL
),
-- 429 — staff (coach / TR) of an active team, who are not on its roster.
staff AS (
  SELECT tc.teams_id AS team, tc.members_id AS member FROM teams_coaches tc
  UNION
  SELECT tr.teams_id, tr.members_id FROM teams_responsibles tr
),
team_activities AS (
  -- ⚠ id cast UP to varchar, never activity_id down to int (see 341).
  SELECT 'training'::varchar AS kind, tr.id::varchar AS activity_id, tr.team
    FROM trainings tr WHERE tr.team IS NOT NULL
  UNION ALL
  SELECT 'game', g.id::varchar, g.kscw_team
    FROM games g WHERE g.kscw_team IS NOT NULL
),
staff_rows AS (
  SELECT p.id AS participation, viewer."user" AS viewer_user
    FROM participations p
    JOIN team_activities a ON a.kind = p.activity_type AND a.activity_id = p.activity_id
    JOIN staff s           ON s.team = a.team AND s.member = p.member
    JOIN teams t           ON t.id = a.team AND t.active
    -- 433: viewers are the roster AND the team's other coaches / TRs.
    JOIN (SELECT team, member FROM member_teams
          UNION
          SELECT team, member FROM staff) r ON r.team = a.team AND r.member <> p.member
    JOIN members viewer    ON viewer.id = r.member
   WHERE viewer."user" IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM member_teams own
                      WHERE own.team = a.team AND own.member = p.member)
)
SELECT participation, viewer_user FROM guest_rows
UNION
SELECT participation, viewer_user FROM staff_rows;

-- ── 3. member_staff_visibility ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS member_staff_visibility (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member      integer NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  viewer_user uuid    NOT NULL REFERENCES directus_users(id) ON DELETE CASCADE,
  CONSTRAINT member_staff_visibility_pair_uniq UNIQUE (member, viewer_user)
);
-- The policy compares viewer_user to $CURRENT_USER.
CREATE INDEX IF NOT EXISTS member_staff_visibility_viewer_idx ON member_staff_visibility (viewer_user);

CREATE OR REPLACE VIEW member_staff_visibility_expected AS
WITH staff AS (
  SELECT tc.teams_id AS team, tc.members_id AS member FROM teams_coaches tc
  UNION
  SELECT tr.teams_id, tr.members_id FROM teams_responsibles tr
)
SELECT DISTINCT s.member, viewer."user" AS viewer_user
  FROM staff s
  JOIN teams t        ON t.id = s.team AND t.active
  JOIN staff o        ON o.team = s.team AND o.member <> s.member
  JOIN members viewer ON viewer.id = o.member
 WHERE viewer."user" IS NOT NULL;

CREATE OR REPLACE FUNCTION verify_member_staff_visibility()
RETURNS TABLE (kind text, member integer, viewer_user uuid)
LANGUAGE sql STABLE AS $$
  SELECT 'missing'::text, e.member, e.viewer_user
    FROM member_staff_visibility_expected e
    LEFT JOIN member_staff_visibility a ON a.member = e.member AND a.viewer_user = e.viewer_user
   WHERE a.member IS NULL
  UNION ALL
  SELECT 'extra'::text, a.member, a.viewer_user
    FROM member_staff_visibility a
    LEFT JOIN member_staff_visibility_expected e ON e.member = a.member AND e.viewer_user = a.viewer_user
   WHERE e.member IS NULL;
$$;

CREATE OR REPLACE FUNCTION refresh_member_staff_visibility()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM member_staff_visibility a
   WHERE NOT EXISTS (SELECT 1 FROM member_staff_visibility_expected e
                      WHERE e.member = a.member AND e.viewer_user = a.viewer_user);
  INSERT INTO member_staff_visibility (member, viewer_user)
  SELECT e.member, e.viewer_user FROM member_staff_visibility_expected e
  ON CONFLICT (member, viewer_user) DO NOTHING;
END $$;

-- ── Triggers ────────────────────────────────────────────────────────────────
-- participation_visibility already listens on every source its view reads
-- (341/429: member_teams, teams, teams_coaches, teams_responsibles, members, …).
CREATE OR REPLACE FUNCTION kscw_av_refresh_trigger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM refresh_absence_visibility();
  RETURN NULL;                       -- AFTER STATEMENT trigger
END $$;

CREATE OR REPLACE FUNCTION kscw_sv_refresh_trigger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM refresh_absence_visibility();
  PERFORM refresh_member_staff_visibility();
  RETURN NULL;
END $$;

-- absences: only the columns the view reads (a reason edit does not move anything).
DROP TRIGGER IF EXISTS trg_av_absences ON absences;
CREATE TRIGGER trg_av_absences
  AFTER INSERT OR DELETE OR UPDATE OF member, id ON absences
  FOR EACH STATEMENT EXECUTE FUNCTION kscw_av_refresh_trigger();

DROP TRIGGER IF EXISTS trg_sv_member_teams ON member_teams;
CREATE TRIGGER trg_sv_member_teams
  AFTER INSERT OR UPDATE OR DELETE ON member_teams
  FOR EACH STATEMENT EXECUTE FUNCTION kscw_sv_refresh_trigger();

DROP TRIGGER IF EXISTS trg_sv_teams_coaches ON teams_coaches;
CREATE TRIGGER trg_sv_teams_coaches
  AFTER INSERT OR UPDATE OR DELETE ON teams_coaches
  FOR EACH STATEMENT EXECUTE FUNCTION kscw_sv_refresh_trigger();

DROP TRIGGER IF EXISTS trg_sv_teams_responsibles ON teams_responsibles;
CREATE TRIGGER trg_sv_teams_responsibles
  AFTER INSERT OR UPDATE OR DELETE ON teams_responsibles
  FOR EACH STATEMENT EXECUTE FUNCTION kscw_sv_refresh_trigger();

-- teams.active gates both; members."user" is the viewer's login. Column-scoped so
-- the syncs' frequent members / teams updates don't reconcile for nothing.
DROP TRIGGER IF EXISTS trg_sv_teams ON teams;
CREATE TRIGGER trg_sv_teams
  AFTER INSERT OR DELETE OR UPDATE OF active, id ON teams
  FOR EACH STATEMENT EXECUTE FUNCTION kscw_sv_refresh_trigger();

DROP TRIGGER IF EXISTS trg_sv_members ON members;
CREATE TRIGGER trg_sv_members
  AFTER INSERT OR DELETE OR UPDATE OF "user", id ON members
  FOR EACH STATEMENT EXECUTE FUNCTION kscw_sv_refresh_trigger();

-- ── Backfill ────────────────────────────────────────────────────────────────
SELECT refresh_absence_visibility();
SELECT refresh_participation_visibility();
SELECT refresh_member_staff_visibility();

