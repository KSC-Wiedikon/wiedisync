-- Migration 437: max participants with a waiting list (trainings + events)
--
-- `trainings.max_participants` and `events.max_players` were saved by the forms but
-- enforced by nothing. The PocketBase hook that did it (participation_priority.pb.js:
-- guests give way to team players, the waiting list moves up when a seat frees) was
-- never ported in the move to Directus (v2.8.0, 2026-03-29) — only the "no guests in
-- games" half survived as trg_participations_guest_block. Since then a full training
-- simply took a 15th Yes and no row ever reached `waitlisted` (0 on prod, 30.10.2026).
--
-- The rule lives in Postgres because most writers bypass Directus hooks: the OpnForm
-- sign-up endpoint, the auto-confirm sweeps and the absence / game-shorten unwinds all
-- write participations with raw SQL.
--
-- The rule, per activity (and per session for per-day event RSVPs):
--   * Seats = non-staff `confirmed` rows plus the +1s they bring (guest_count) — the
--     sum the roster modal shows as "Full (x/y)" and the season-health check uses.
--   * Everybody asking for a seat (`confirmed` or `waitlisted`) is ranked:
--       1. team players before guest players (member_teams.guest_level > 0), lower
--          guest levels before higher ones;
--       2. then first come, first served (`claimed_at`).
--     Seats go down that list until the next person (with their +1s) does not fit;
--     that person and everybody after them are `waitlisted`. So:
--       - a guest who says Yes to a full activity goes on the waiting list;
--       - a team player who says Yes to a full activity takes the seat of the guest
--         who claimed last (highest guest level first), who goes on the waiting list;
--         with no guest holding a seat, the player goes on the waiting list;
--       - a seat that frees up (No, Maybe, delete, absence, staff flag, fewer +1s, a
--         higher cap, the cap removed) goes to the first person on the waiting list;
--       - a lower cap moves the last-ranked people onto the waiting list.
--   * `claimed_at` is stamped when a row ENTERS confirmed/waitlisted from anything
--     else. Moving between the two keeps it: a bumped guest keeps their place in the
--     queue, and tapping Yes again cannot jump it. Coming back after a No (or an
--     absence) is a new claim at the back.
--   * Staff rows, `tentative` and `declined` never take a seat.
--   * An activity that is cancelled or over is left alone: a coach confirming after
--     the training who actually came must not push anybody onto a waiting list.
--
-- Every seat change the rebalance makes to SOMEBODY ELSE's row (not the row the
-- writer just wrote) is queued in `participation_capacity_moves`; kscw-hooks drains
-- the queue into the bell + a push ("you are on the waiting list" / "you got a seat").
--
-- `waitlisted_at` keeps its meaning for real waiting-list rows (set on entry, cleared
-- on the way out unless the writer sets it) — the roster sorts the waiting list by it.
-- ⚠ It is ALSO the 1970-01-01 "auto-decline created this row" sentinel (absence and
-- game-shorten unwinds, migration 345). Those rows are `declined`; nothing here
-- touches a declined row's waitlisted_at.

BEGIN;

-- ── (1) When this person asked for a seat ─────────────────────────────
ALTER TABLE participations ADD COLUMN IF NOT EXISTS claimed_at timestamptz;

COMMENT ON COLUMN public.participations.claimed_at IS
  'System-set (trg_participations_capacity_stamp): when this row entered confirmed/waitlisted '
  'from another status. First come, first served order for max_participants / max_players; '
  'unchanged when the capacity rebalance moves the row between confirmed and waitlisted. '
  'NULL when the row holds no claim (declined / tentative / never answered).';

-- Existing seat claims get their time now, BEFORE the stamp trigger below exists (it
-- ignores written values). Without it they would rank behind every new Yes, and the
-- first write to a full activity would bump people who answered weeks ago. Raw-SQL
-- writers (auto-confirm) leave date_created empty, hence the epoch floor: no time
-- known = earliest. Games never take part, so the games-only guest block is not hit.
UPDATE participations
   SET claimed_at = COALESCE(last_status_edited_at, date_created, date_updated, TIMESTAMPTZ 'epoch')
 WHERE claimed_at IS NULL
   AND activity_type IN ('training', 'event')
   AND status IN ('confirmed', 'waitlisted');

-- ── (2) The outbox kscw-hooks turns into bell + push ──────────────────
CREATE TABLE IF NOT EXISTS participation_capacity_moves (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participation integer REFERENCES participations(id) ON DELETE CASCADE,
  member integer NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  activity_type character varying(16) NOT NULL,
  activity_id character varying(255) NOT NULL,
  session_id character varying(255),
  move character varying(16) NOT NULL,
  date_created timestamptz NOT NULL DEFAULT now(),
  notified_at timestamptz,
  CONSTRAINT participation_capacity_moves_move_chk CHECK (move IN ('confirmed', 'waitlisted'))
);

COMMENT ON TABLE public.participation_capacity_moves IS
  'Seat changes made by kscw_rebalance_capacity to somebody else''s RSVP (bumped to the waiting '
  'list, or promoted from it). kscw-hooks claims rows with notified_at IS NULL, writes the bell '
  'notification + push, and deletes claimed rows after 30 days. Not a Directus collection.';

CREATE INDEX IF NOT EXISTS participation_capacity_moves_pending_idx
  ON participation_capacity_moves (id) WHERE notified_at IS NULL;

-- ── (3) Guest level of a member for an activity ───────────────────────
-- 0 = team player (or not on any roster of the activity: role / named invite /
-- club-wide event). Training: the training's team. Event: the lowest level across
-- the event's teams — a core player on one invited team is a player for the event,
-- the same reading as the guest RSVP gate (kscw-hooks assertGuestMayRsvp).
CREATE OR REPLACE FUNCTION kscw_capacity_guest_level(p_type text, p_activity text, p_team integer, p_member integer)
RETURNS integer
LANGUAGE sql STABLE
SET search_path = public
AS $$
  SELECT COALESCE(CASE
    WHEN p_type = 'training' THEN (
      SELECT min(COALESCE(mt.guest_level, 0)) FROM member_teams mt
       WHERE mt.team = p_team AND mt.member = p_member)
    WHEN p_type = 'event' THEN (
      SELECT min(COALESCE(mt.guest_level, 0)) FROM member_teams mt
        JOIN events_teams et ON et.teams_id = mt.team
       WHERE et.events_id = p_activity::integer AND mt.member = p_member)
  END, 0)
$$;

-- ── (4) Cap, team and "leave it alone" of an activity ────────────────
CREATE OR REPLACE FUNCTION kscw_activity_capacity(p_type text, p_activity text,
  OUT cap integer, OUT team integer, OUT closed boolean)
RETURNS SETOF record
LANGUAGE sql STABLE
SET search_path = public
AS $$
  SELECT NULLIF(GREATEST(COALESCE(t.max_participants, 0), 0), 0), t.team,
         COALESCE(t.cancelled OR t.date < (now() AT TIME ZONE 'Europe/Zurich')::date, false)
    FROM trainings t
   WHERE p_type = 'training' AND t.id = p_activity::integer
  UNION ALL
  SELECT NULLIF(GREATEST(COALESCE(e.max_players, 0), 0), 0), NULL::integer,
         COALESCE(e.cancelled OR COALESCE(e.end_date, e.start_date) < now(), false)
    FROM events e
   WHERE p_type = 'event' AND e.id = p_activity::integer
$$;

-- ── (5) The rebalance ─────────────────────────────────────────────────
-- Returns how many rows it moved. p_written = the row the caller just wrote (its
-- own move is the writer's answer, not news to push); NULL for a cap change.
CREATE OR REPLACE FUNCTION kscw_rebalance_capacity(p_type text, p_activity text, p_session text, p_written integer DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_cap integer;
  v_team integer;
  v_closed boolean;
  v_moved integer := 0;
BEGIN
  IF p_type IS NULL OR p_type NOT IN ('training', 'event')
     OR p_activity IS NULL OR p_activity !~ '^[0-9]{1,9}$' THEN
    RETURN 0;
  END IF;

  -- Most activities have no cap: leave before the lock when there is nothing to do
  -- (no cap and nobody waiting), or the activity is over / cancelled / gone.
  SELECT c.cap, c.closed INTO v_cap, v_closed FROM kscw_activity_capacity(p_type, p_activity) c;
  IF NOT FOUND OR v_closed THEN
    RETURN 0;
  END IF;
  IF v_cap IS NULL AND NOT EXISTS (
    SELECT 1 FROM participations p
     WHERE p.activity_type = p_type AND p.activity_id = p_activity
       AND p.session_id IS NOT DISTINCT FROM p_session
       AND p.status = 'waitlisted') THEN
    RETURN 0;
  END IF;

  -- One rebalance per activity at a time. Two Yes taps racing for the last seat
  -- queue here, and the second one's statements see the first one's commit
  -- (READ COMMITTED takes a fresh snapshot per statement). An advisory lock rather
  -- than FOR UPDATE on the activity row, so a coach saving the training form does
  -- not wait behind (or deadlock with) RSVPs. A deadlock is still possible when two
  -- writers each move the other's row in the same instant; Postgres then aborts one
  -- of them, and that member gets the app's save error and taps again.
  PERFORM pg_advisory_xact_lock(437, hashtext(p_type || ':' || p_activity));

  -- Read again under the lock: the cap may have changed while we waited.
  SELECT c.cap, c.team, c.closed INTO v_cap, v_team, v_closed FROM kscw_activity_capacity(p_type, p_activity) c;
  IF NOT FOUND OR v_closed THEN
    RETURN 0;
  END IF;

  -- The UPDATE below re-fires trg_participations_capacity on every row it moves;
  -- this flag makes those calls return at once. Transaction-local.
  PERFORM set_config('kscw.capacity_rebalancing', 'on', true);

  WITH pool AS (
    SELECT p.id, p.member,
           1 + GREATEST(COALESCE(p.guest_count, 0), 0) AS seats,
           kscw_capacity_guest_level(p_type, p_activity, v_team, p.member) AS lvl,
           p.claimed_at AS claimed
      FROM participations p
     WHERE p.activity_type = p_type
       AND p.activity_id = p_activity
       AND p.session_id IS NOT DISTINCT FROM p_session
       AND NOT p.is_staff
       AND p.status IN ('confirmed', 'waitlisted')
  ), ranked AS (
    SELECT id,
           CASE
             WHEN v_cap IS NULL THEN 'confirmed'
             WHEN sum(seats) OVER (ORDER BY (lvl > 0), lvl, claimed NULLS FIRST, id
                                   ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) <= v_cap
               THEN 'confirmed'
             ELSE 'waitlisted'
           END AS want
      FROM pool
  ), moved AS (
    UPDATE participations p
       SET status = r.want
      FROM ranked r
     WHERE p.id = r.id
       AND p.status IS DISTINCT FROM r.want
    RETURNING p.id, p.member, p.status, p.claimed_at
  ), queued AS (
    INSERT INTO participation_capacity_moves (participation, member, activity_type, activity_id, session_id, move)
    SELECT m.id, m.member, p_type, p_activity, p_session, m.status
      FROM moved m
     WHERE m.id IS DISTINCT FROM p_written
       AND m.member IS NOT NULL
       -- Claimed inside this transaction = never seen with a seat: an auto-confirm
       -- sweep or a revert writing many rows at once must not push each overflow.
       AND COALESCE(m.claimed_at, '-infinity'::timestamptz) < transaction_timestamp()
    RETURNING 1
  )
  SELECT count(*) INTO v_moved FROM moved;

  PERFORM set_config('kscw.capacity_rebalancing', 'off', true);
  RETURN v_moved;
END;
$$;

-- ── (6) Stamp claimed_at / waitlisted_at ──────────────────────────────
-- claimed_at belongs to this trigger alone: members hold create/update on their own
-- participations with every field, so a written value is ignored — otherwise a
-- backdated claimed_at would jump the queue. Fires on every INSERT/UPDATE for that.
CREATE OR REPLACE FUNCTION trg_participations_capacity_stamp()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.claimed_at := CASE WHEN NEW.status IN ('confirmed', 'waitlisted') THEN clock_timestamp() END;
  ELSIF NEW.status IN ('confirmed', 'waitlisted')
        AND (OLD.status IS NULL OR OLD.status NOT IN ('confirmed', 'waitlisted')) THEN
    NEW.claimed_at := clock_timestamp();
  ELSE
    NEW.claimed_at := OLD.claimed_at;
  END IF;

  IF NEW.status = 'waitlisted' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'waitlisted') THEN
    NEW.waitlisted_at := clock_timestamp();
  ELSIF TG_OP = 'UPDATE' AND OLD.status = 'waitlisted' AND NEW.status IS DISTINCT FROM 'waitlisted'
        AND NEW.waitlisted_at IS NOT DISTINCT FROM OLD.waitlisted_at THEN
    NEW.waitlisted_at := NULL;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_participations_capacity_stamp ON participations;
CREATE TRIGGER trg_participations_capacity_stamp
  BEFORE INSERT OR UPDATE ON participations
  FOR EACH ROW EXECUTE FUNCTION trg_participations_capacity_stamp();

-- ── (7) Rebalance after every write that can change the seats ─────────
CREATE OR REPLACE FUNCTION trg_participations_capacity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF current_setting('kscw.capacity_rebalancing', true) = 'on' THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF OLD.activity_type IN ('training', 'event')
       AND OLD.status IN ('confirmed', 'waitlisted') AND NOT OLD.is_staff THEN
      PERFORM kscw_rebalance_capacity(OLD.activity_type, OLD.activity_id, OLD.session_id, NULL);
    END IF;
    RETURN NULL;
  END IF;

  IF NEW.activity_type IS NULL OR NEW.activity_type NOT IN ('training', 'event') THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.status IN ('confirmed', 'waitlisted') AND NOT NEW.is_staff THEN
      PERFORM kscw_rebalance_capacity(NEW.activity_type, NEW.activity_id, NEW.session_id, NEW.id);
    END IF;
    RETURN NULL;
  END IF;

  IF ((OLD.status IN ('confirmed', 'waitlisted') AND NOT OLD.is_staff)
      OR (NEW.status IN ('confirmed', 'waitlisted') AND NOT NEW.is_staff))
     AND (OLD.status IS DISTINCT FROM NEW.status
          OR OLD.is_staff IS DISTINCT FROM NEW.is_staff
          OR OLD.guest_count IS DISTINCT FROM NEW.guest_count) THEN
    PERFORM kscw_rebalance_capacity(NEW.activity_type, NEW.activity_id, NEW.session_id, NEW.id);
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_participations_capacity ON participations;
CREATE TRIGGER trg_participations_capacity
  AFTER INSERT OR DELETE OR UPDATE OF status, is_staff, guest_count ON participations
  FOR EACH ROW EXECUTE FUNCTION trg_participations_capacity();

-- ── (8) Rebalance when the cap changes or the activity is un-cancelled ─
CREATE OR REPLACE FUNCTION trg_activity_capacity_changed()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_type text := CASE TG_TABLE_NAME WHEN 'trainings' THEN 'training' ELSE 'event' END;
  v_session text;
BEGIN
  FOR v_session IN
    SELECT DISTINCT p.session_id FROM participations p
     WHERE p.activity_type = v_type
       AND p.activity_id = NEW.id::text
       AND p.status IN ('confirmed', 'waitlisted')
       AND NOT p.is_staff
  LOOP
    PERFORM kscw_rebalance_capacity(v_type, NEW.id::text, v_session, NULL);
  END LOOP;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_trainings_capacity_changed ON trainings;
CREATE TRIGGER trg_trainings_capacity_changed
  AFTER UPDATE OF max_participants, cancelled ON trainings
  FOR EACH ROW WHEN (OLD.max_participants IS DISTINCT FROM NEW.max_participants
                     OR (OLD.cancelled AND NOT NEW.cancelled))
  EXECUTE FUNCTION trg_activity_capacity_changed();

DROP TRIGGER IF EXISTS trg_events_capacity_changed ON events;
CREATE TRIGGER trg_events_capacity_changed
  AFTER UPDATE OF max_players, cancelled ON events
  FOR EACH ROW WHEN (OLD.max_players IS DISTINCT FROM NEW.max_players
                     OR (OLD.cancelled AND NOT NEW.cancelled))
  EXECUTE FUNCTION trg_activity_capacity_changed();

-- ── (9) Directus admin metadata ───────────────────────────────────────
-- ⚠ NULL in a VALUES list types as text and `options` is json.
INSERT INTO directus_fields (collection, field, interface, options, readonly, hidden, sort, width, note)
SELECT 'participations', 'claimed_at', 'datetime', NULL::json, true, false, NULL::integer, 'half',
       'System-set: when this person asked for a seat. Order of the waiting list for max participants.'
WHERE NOT EXISTS (
  SELECT 1 FROM directus_fields WHERE collection = 'participations' AND field = 'claimed_at'
);

COMMIT;

