-- Migration 230: Basketplan person staging + nation lookup.
--
-- Basketplan (Swiss Basketball, club 166) is the ISSUING authority for basketball
-- licences and — unlike every register we already mirror — carries nationality on
-- 100% of licensed people. It is reached only through an authenticated browser
-- session (the login hashes the password client-side, so no curl), so this is a
-- Playwright scrape into a staging table, mirroring the ClubDesk pattern:
-- scrape -> staging -> FILL-ONLY passes, never a direct write to members.
--
-- ── basketplan_nations ───────────────────────────────────────────────────────
-- Basketplan's nationality picklist is 297 options whose VALUE is an internal
-- numeric id and whose LABEL is a FRENCH country name — hardcoded, identical
-- under locale=de/it/fr. So neither our German/English COUNTRY_NAME_TO_CODE nor
-- Intl at runtime can resolve it; the numeric id is the only stable key, and it
-- is mapped once, here.
--
-- ⚠ 116 of the 296 options are NOT mapped, on purpose. 93 are legacy
-- abbreviation entries (`D`, `ALL`, `A`, `BRD`, `YUG`, `MAC`, `CH1`,
-- `Suisse pour FSBA`…) that coexist as SEPARATE options beside the proper names
-- and are still in live use; some are genuinely ambiguous (`MAC` = Macedonia or
-- Macao?). The rest are territories outside our 196-country list (Aruba, Guam,
-- Palau, Puerto Rico, the Virgin Islands…). All are stored with iso = NULL and
-- ambiguous = true so the fill pass SKIPS them and reports them for a human,
-- rather than guessing a nationality onto a real person. Observed impact is
-- small: in an 86-person sample only two assertions were unmapped (`MAC` x1,
-- `D` x1) out of 90 — `D` is almost certainly Germany but is deliberately left
-- for a human to confirm.
--
-- ── basketplan_people ────────────────────────────────────────────────────────
-- One row per scraped person, keyed by Basketplan's personId. Deliberately holds
-- ONLY what we intend to consume — nationality, the officials qualifications and
-- their acquisition dates, the trained-in-Switzerland flag and licence number.
-- Addresses, birthdates, AHV and IBAN are NOT staged: Basketplan's addresses are
-- frequently worse than ours (`Hagenbuchrain` vs our correct `Hagenbuchrain 38`),
-- it holds at least one corrupt birthdate ("0996"), and the AHV/IBAN fields are
-- sparse, high-sensitivity and visible for minors. Not staging them is the
-- simplest guarantee they can never leak into members.
--
-- Schema-only + idempotent.

