CREATE TABLE IF NOT EXISTS basketplan_people (
  person_id      integer PRIMARY KEY,
  last_name      text,
  first_name     text,
  birthdate      date,
  licence_nr     text,
  nation1_id     integer,
  nation2_id     integer,
  nation_confirmed boolean,
  trained_in_ch  boolean,
  otr1_since     date,
  otr2_since     date,
  otn1_since     date,
  otn2_since     date,
  referee_reg_since  date,
  referee_nat_since  date,
  referee_mini_since date,
  referee_youth_since date,
  last_scored_at date,
  scraped_at     timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE basketplan_people IS
  'Staging for the authenticated Basketplan person scrape (findPersonById.do). Holds only the fields we intend to consume — no address / AHV / IBAN, and birthdate is a cross-check aid only, never an overwrite source.';

CREATE INDEX IF NOT EXISTS basketplan_people_licence_nr_idx ON basketplan_people (licence_nr);

