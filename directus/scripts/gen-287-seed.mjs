/**
 * Emits the seed body of migration 287 from COMMITTED repo files only:
 *
 *   src/modules/gameScheduling/data/basketballGroups.ts   — group membership, label, sex,
 *                                                            and the KSCW_TEAM_GROUP map
 *   src/modules/gameScheduling/data/bbGroupFormat.json    — format, gamesTotal, modus
 *                                                            (transcribed from the ProBasket
 *                                                            workbook; see that file's header)
 *
 * Deliberately does NOT read the .xlsx: the workbook lives outside the repo and is not
 * committed, so a generator depending on it could not be re-run from a clean checkout. The
 * workbook's figures already live in bbGroupFormat.json, validated group-by-group on
 * 2026-08-06 (all 16 team counts agree).
 *
 * Usage: node directus/scripts/gen-287-seed.mjs > /tmp/287-seed.sql
 */
import { readFileSync } from 'node:fs'

const SRC = new URL('../../src/modules/gameScheduling/data/basketballGroups.ts', import.meta.url)
const FMT = new URL('../../src/modules/gameScheduling/data/bbGroupFormat.json', import.meta.url)

const src = readFileSync(SRC, 'utf8')
const fmt = JSON.parse(readFileSync(FMT, 'utf8')).groups

const q = (s) => (s == null || s === '' ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`)
const num = (n) => (typeof n === 'number' && Number.isFinite(n) ? String(n) : 'NULL')

// ── groups + their teams ─────────────────────────────────────────────────────
const blocks = src.slice(src.indexOf('BB_GROUPS')).split(/^  "/m).slice(1)
const groups = []
for (const b of blocks) {
  const code = b.slice(0, b.indexOf('"'))
  const label = (b.match(/label:\s*"([^"]+)"/) || [])[1]
  const sex = (b.match(/sex:\s*"([^"]+)"/) || [])[1]
  const teams = [...b.matchAll(/\{\s*name:\s*"([^"]*)"\s*,\s*club:\s*(?:"([^"]*)"|null)\s*\}/g)]
    .map((m) => ({ name: m[1], club: m[2] ?? null }))
  if (!teams.length) continue
  const f = fmt[code] || {}
  groups.push({ code, label, sex, teams, format: f.status ?? 'provisional', games: f.gamesTotal, modus: f.modus, note: f.note })
}

// ── bb_source_id → (group code, workbook team name) ──────────────────────────
// ⚠ The group alone is NOT enough to identify the row. DU18/U20 Rookie holds TWO Wiedikon
// entries (DU18 A and DU18 B), so a group-only match linked 5697 to BOTH — silently giving a
// squad that has no `teams` row the other squad's identity, and mis-scoping its slots.
// The exact workbook name is carried in each mapping's trailing `→ …` comment; require it.
const teamGroup = [...src.slice(src.indexOf('KSCW_TEAM_GROUP'))
  .matchAll(/"(\d+)":\s*"([^"]+)",\s*\/\/[^\n]*?→\s*([^\n]+)/g)]
  .map((m) => ({ bbId: m[1], code: m[2], name: m[3].trim() }))

const allKeys = [...src.slice(src.indexOf('KSCW_TEAM_GROUP')).matchAll(/"(\d+)":\s*"[^"]+"/g)].length
if (teamGroup.length !== allKeys) {
  throw new Error(
    `KSCW_TEAM_GROUP: ${allKeys} entries but only ${teamGroup.length} carry a "→ <workbook name>" ` +
    'comment. Add it — the name is required to identify the row inside its group.')
}

const teamRows = groups.flatMap((g) => g.teams.map((t) => ({ code: g.code, ...t })))

const out = []
out.push(`-- ${groups.length} groups · ${teamRows.length} team rows · ${teamGroup.length} KSCW links.`)
out.push('-- Generated by directus/scripts/gen-287-seed.mjs — do not hand-edit; re-run it.')
out.push('')
out.push('INSERT INTO basketball_groups (season, code, label, sex, format, games_total, modus, note)')
out.push('SELECT s.id, v.code, v.label, v.sex, v.format, v.games_total, v.modus, v.note')
out.push('FROM game_scheduling_seasons s, (VALUES')
out.push(groups.map((g) =>
  `  (${q(g.code)}, ${q(g.label)}, ${q(g.sex)}, ${q(g.format)}, ${num(g.games)}::int, ${q(g.modus)}, ${q(g.note)})`).join(',\n'))
out.push(') AS v(code, label, sex, format, games_total, modus, note)')
out.push("WHERE s.season = '2026/27'")
out.push('ON CONFLICT (season, code) DO UPDATE SET')
out.push('  label = EXCLUDED.label, sex = EXCLUDED.sex, format = EXCLUDED.format,')
out.push('  games_total = EXCLUDED.games_total, modus = EXCLUDED.modus, note = EXCLUDED.note,')
out.push('  date_updated = now();')
out.push('')
out.push('INSERT INTO basketball_group_teams (group_id, team_name, club_name)')
out.push('SELECT g.id, v.team_name, v.club_name')
out.push('FROM basketball_groups g')
out.push("JOIN game_scheduling_seasons s ON s.id = g.season AND s.season = '2026/27'")
out.push('JOIN (VALUES')
out.push(teamRows.map((t) => `  (${q(t.code)}, ${q(t.name)}, ${q(t.club)})`).join(',\n'))
out.push(') AS v(code, team_name, club_name) ON v.code = g.code')
out.push('ON CONFLICT (group_id, team_name) DO UPDATE SET club_name = EXCLUDED.club_name;')
out.push('')
out.push('-- Our own rows. The TEAM is identified by bb_source_id (never by name — prod team 72 is')
out.push('-- called "2xDU18" but plays DU16); the ROW is identified by (group, exact workbook name),')
out.push('-- because DU18/U20 Rookie holds two Wiedikon entries and a group-only match claims both.')
out.push('UPDATE basketball_group_teams gt SET kscw_team = t.id')
out.push('FROM basketball_groups g, game_scheduling_seasons s, teams t, (VALUES')
out.push(teamGroup.map((x) => `  (${q(x.bbId)}, ${q(x.code)}, ${q(x.name)})`).join(',\n'))
out.push(') AS v(bb_source_id, code, team_name)')
out.push("WHERE gt.group_id = g.id AND g.season = s.id AND s.season = '2026/27'")
out.push('  AND g.code = v.code AND gt.team_name = v.team_name')
out.push('  AND t.bb_source_id = v.bb_source_id AND t.sport = \'basketball\' AND t.active')
out.push('  AND gt.kscw_team IS DISTINCT FROM t.id;')
out.push('')
out.push('-- Opponent clubs, by EXACT name only. A fuzzy match here would mis-address a')
out.push('-- scheduling link; NULL is visible and harmless, a wrong club is neither.')
out.push('--')
out.push('-- ⚠ `is_own_club` is excluded. Two of our own rows carry no kscw_team — DU18 B (no')
out.push('-- `teams` row yet) and DU10 (no active team) — so a kscw_team-only guard let them match')
out.push('-- KSC Wiedikon itself and be filed as opponents, which would pair the club against')
out.push('-- itself in its own portal.')
out.push('UPDATE basketball_group_teams gt SET bp_club = c.id')
out.push('FROM basketplan_clubs c')
out.push('WHERE gt.kscw_team IS NULL AND gt.club_name IS NOT NULL')
out.push('  AND c.name = gt.club_name AND c.is_own_club IS NOT TRUE')
out.push('  AND gt.bp_club IS DISTINCT FROM c.id;')
out.push('')
out.push('-- Converge the other way too: clear any own-club link a previous run may have set.')
out.push('UPDATE basketball_group_teams gt SET bp_club = NULL')
out.push('FROM basketplan_clubs c')
out.push('WHERE gt.bp_club = c.id AND c.is_own_club IS TRUE;')

console.log(out.join('\n'))
